export function translate(locale: Locale, key: keyof Copy) {
  return dictionaries[locale][key] ?? dictionaries.en[key];
}

export function text(locale: Locale, value: string) {
  if (value in dictionaries.en) return translate(locale, value as keyof Copy);
  return value;
}

function detectLocale(): Locale {
  const saved = window.localStorage.getItem(LOCALE_KEY);
  if (isLocale(saved)) return saved;
  const prefix = navigator.language.toLowerCase().slice(0, 2);
  return isLocale(prefix) ? prefix : "en";
}

function subscribeLocale(onChange: () => void) {
  window.addEventListener("aibay-locale", onChange);
  window.addEventListener("storage", onChange);
  return () => {
    window.removeEventListener("aibay-locale", onChange);
    window.removeEventListener("storage", onChange);
  };
}

function getLocaleSnapshot() {
  return detectLocale();
}

function getServerLocaleSnapshot(): Locale {
  return "en";
}

export function setLocale(locale: Locale) {
  window.localStorage.setItem(LOCALE_KEY, locale);
  window.dispatchEvent(new Event("aibay-locale"));
}

export function useI18n() {
  const locale = useSyncExternalStore(subscribeLocale, getLocaleSnapshot, getServerLocaleSnapshot);
  return {
    locale,
    setLocale,
    t: (key: keyof Copy) => translate(locale, key),
    text: (value: string) => text(locale, value),
  };
}
